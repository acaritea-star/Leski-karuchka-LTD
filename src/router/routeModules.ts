const attempts = new Map<string, number>();
export function warmRoute(path: string) {
  const name = paths[path] ?? (path.startsWith('/novini/') ? 'NewsArticlePage' : path.startsWith('/admin/news/') ? 'AdminNewsEdit' : undefined);
  if (!name || (attempts.get(name) ?? 0) > Date.now()) return;
  attempts.set(name, Infinity);
  void routeModules[name]().catch(() => { attempts.set(name, Date.now() + 5000); });
}

